const JOURNEY_PAGE_JSX = `import { useState } from 'react'
import { useNavigate, Link } from 'react-router-dom'
import { steps, routePaths, fieldKey, FIELD_TYPES } from '../lib/journey.js'
import { useForm } from '../store.jsx'
import Layout from './Layout.jsx'
import BackLink from './BackLink.jsx'
import ErrorSummary from './ErrorSummary.jsx'

function isFieldEmpty(type, v) {
  if (type === 'checkboxes') return !Array.isArray(v) || v.length === 0
  if (type === 'date-input') return !v || !v.day || !v.month || !v.year
  return v === undefined || v === null || String(v).trim() === ''
}

function formatValue(type, v) {
  if (v === undefined || v === null || v === '') return 'Not provided'
  if (type === 'checkboxes') return Array.isArray(v) ? v.join(', ') : 'Not provided'
  if (type === 'date-input') return [v.day, v.month, v.year].filter(Boolean).join(' / ') || 'Not provided'
  return String(v)
}

export default function JourneyPage({ index }) {
  const step = steps[index]
  const navigate = useNavigate()
  const { values, setValue } = useForm()
  const [errors, setErrors] = useState([])

  const prevPath = index > 0 ? routePaths[index - 1] : null
  const nextPath = index < steps.length - 1 ? routePaths[index + 1] : null

  const enriched = step.components.map((c, i) =>
    Object.assign({}, c, { key: fieldKey(step, c, i), _index: i }),
  )
  const fields = enriched.filter((c) => FIELD_TYPES.indexOf(c.type) !== -1)
  const hasConfirmation = step.components.some((c) => c.type === 'confirmation')
  const buttonComp = step.components.find((c) => c.type === 'button')
  const actionLabel = buttonComp && buttonComp.label ? buttonComp.label : 'Continue'
  const isStart = !!buttonComp && /start/i.test(buttonComp.label || '')

  function handleSubmit(e) {
    e.preventDefault()
    const errs = fields
      .filter((f) => isFieldEmpty(f.type, values[f.key]))
      .map((f) => ({ key: f.key, message: (f.label || 'This field') + ' is required' }))
    setErrors(errs)
    if (errs.length > 0) {
      window.scrollTo(0, 0)
      return
    }
    if (nextPath) navigate(nextPath)
  }

  function toggleCheckbox(key, option) {
    const current = Array.isArray(values[key]) ? values[key] : []
    if (current.indexOf(option) === -1) setValue(key, current.concat(option))
    else setValue(key, current.filter((o) => o !== option))
  }

  function renderComponent(c) {
    const key = c.key
    const errored = errors.some((er) => er.key === key)
    const groupClass = 'govuk-form-group' + (errored ? ' govuk-form-group--error' : '')

    switch (c.type) {
      case 'paragraph':
        return (
          <p className="govuk-body" key={c._index}>
            {c.text}
          </p>
        )

      case 'text-input':
        return (
          <div className={groupClass} key={c._index}>
            <label className="govuk-label" htmlFor={key}>
              {c.label}
            </label>
            {c.hint ? <div className="govuk-hint">{c.hint}</div> : null}
            {errored ? <p className="govuk-error-message">{c.label} is required</p> : null}
            <input
              className="govuk-input"
              id={key}
              name={key}
              type="text"
              value={values[key] || ''}
              onChange={(e) => setValue(key, e.target.value)}
            />
          </div>
        )

      case 'textarea':
        return (
          <div className={groupClass} key={c._index}>
            <label className="govuk-label" htmlFor={key}>
              {c.label}
            </label>
            {c.hint ? <div className="govuk-hint">{c.hint}</div> : null}
            {errored ? <p className="govuk-error-message">{c.label} is required</p> : null}
            <textarea
              className="govuk-textarea"
              id={key}
              name={key}
              rows={5}
              value={values[key] || ''}
              onChange={(e) => setValue(key, e.target.value)}
            />
          </div>
        )

      case 'radios':
        return (
          <div className={groupClass} key={c._index}>
            <fieldset className="govuk-fieldset">
              <legend className="govuk-fieldset__legend">{c.label}</legend>
              {c.hint ? <div className="govuk-hint">{c.hint}</div> : null}
              {errored ? <p className="govuk-error-message">{c.label} is required</p> : null}
              <div className="govuk-radios">
                {(c.options || ['Yes', 'No']).map((opt, oi) => (
                  <div className="govuk-radios__item" key={oi}>
                    <input
                      className="govuk-radios__input"
                      id={key + '-' + oi}
                      name={key}
                      type="radio"
                      value={opt}
                      checked={values[key] === opt}
                      onChange={() => setValue(key, opt)}
                    />
                    <label className="govuk-label govuk-radios__label" htmlFor={key + '-' + oi}>
                      {opt}
                    </label>
                  </div>
                ))}
              </div>
            </fieldset>
          </div>
        )

      case 'checkboxes':
        return (
          <div className={groupClass} key={c._index}>
            <fieldset className="govuk-fieldset">
              <legend className="govuk-fieldset__legend">{c.label}</legend>
              {c.hint ? <div className="govuk-hint">{c.hint}</div> : null}
              {errored ? <p className="govuk-error-message">{c.label} is required</p> : null}
              <div className="govuk-checkboxes">
                {(c.options || []).map((opt, oi) => (
                  <div className="govuk-checkboxes__item" key={oi}>
                    <input
                      className="govuk-checkboxes__input"
                      id={key + '-' + oi}
                      name={key}
                      type="checkbox"
                      value={opt}
                      checked={Array.isArray(values[key]) && values[key].indexOf(opt) !== -1}
                      onChange={() => toggleCheckbox(key, opt)}
                    />
                    <label className="govuk-label govuk-checkboxes__label" htmlFor={key + '-' + oi}>
                      {opt}
                    </label>
                  </div>
                ))}
              </div>
            </fieldset>
          </div>
        )

      case 'date-input': {
        const dv = values[key] || {}
        return (
          <div className={groupClass} key={c._index}>
            <fieldset className="govuk-fieldset">
              <legend className="govuk-fieldset__legend">{c.label}</legend>
              {c.hint ? <div className="govuk-hint">{c.hint}</div> : null}
              {errored ? <p className="govuk-error-message">{c.label} is required</p> : null}
              <div className="govuk-date-input" id={key}>
                {['day', 'month', 'year'].map((part) => (
                  <div className="govuk-date-input__item" key={part}>
                    <label
                      className="govuk-label govuk-date-input__label"
                      htmlFor={key + '-' + part}
                    >
                      {part.charAt(0).toUpperCase() + part.slice(1)}
                    </label>
                    <input
                      className={
                        'govuk-input govuk-date-input__input ' +
                        (part === 'year' ? 'govuk-input--width-4' : 'govuk-input--width-2')
                      }
                      id={key + '-' + part}
                      name={key + '-' + part}
                      type="text"
                      inputMode="numeric"
                      value={dv[part] || ''}
                      onChange={(e) => setValue(key, Object.assign({}, dv, { [part]: e.target.value }))}
                    />
                  </div>
                ))}
              </div>
            </fieldset>
          </div>
        )
      }

      case 'file-upload':
        return (
          <div className={groupClass} key={c._index}>
            <label className="govuk-label" htmlFor={key}>
              {c.label}
            </label>
            {c.hint ? <div className="govuk-hint">{c.hint}</div> : null}
            {errored ? <p className="govuk-error-message">{c.label} is required</p> : null}
            <input
              className="govuk-file-upload"
              id={key}
              name={key}
              type="file"
              onChange={(e) =>
                setValue(key, e.target.files && e.target.files[0] ? e.target.files[0].name : '')
              }
            />
          </div>
        )

      case 'summary-list': {
        const rows = []
        steps.forEach((s, si) => {
          if (si >= index) return
          s.components.forEach((sc, sci) => {
            if (FIELD_TYPES.indexOf(sc.type) === -1) return
            const k = fieldKey(s, sc, sci)
            rows.push({
              label: sc.label || sc.type,
              value: formatValue(sc.type, values[k]),
              to: routePaths[si],
            })
          })
        })
        return (
          <dl className="govuk-summary-list" key={c._index}>
            {rows.length === 0 ? (
              <div className="govuk-summary-list__row">
                <dt className="govuk-summary-list__key">No answers yet</dt>
                <dd className="govuk-summary-list__value" />
                <dd className="govuk-summary-list__actions" />
              </div>
            ) : (
              rows.map((r, ri) => (
                <div className="govuk-summary-list__row" key={ri}>
                  <dt className="govuk-summary-list__key">{r.label}</dt>
                  <dd className="govuk-summary-list__value">{r.value}</dd>
                  <dd className="govuk-summary-list__actions">
                    <Link to={r.to}>Change</Link>
                  </dd>
                </div>
              ))
            )}
          </dl>
        )
      }

      case 'confirmation':
        return (
          <div className="govuk-panel govuk-panel--confirmation" key={c._index}>
            <h1 className="govuk-panel__title">{c.text || 'Application complete'}</h1>
          </div>
        )

      case 'button':
      default:
        return null
    }
  }

  return (
    <Layout>
      {prevPath ? <BackLink to={prevPath} /> : null}
      <ErrorSummary errors={errors} />
      {!hasConfirmation ? (
        <h1 className="govuk-heading-l">{step.heading || step.title}</h1>
      ) : null}
      {!hasConfirmation && step.description ? (
        <p className="govuk-body">{step.description}</p>
      ) : null}

      {hasConfirmation ? (
        <div>
          {enriched.map(renderComponent)}
          {step.description ? <p className="govuk-body">{step.description}</p> : null}
          {index > 0 ? (
            <p className="govuk-body">
              <Link to={routePaths[0]}>Return to the start</Link>
            </p>
          ) : null}
        </div>
      ) : (
        <form onSubmit={handleSubmit} noValidate>
          {enriched.map(renderComponent)}
          <button
            type="submit"
            className={'govuk-button' + (isStart ? ' govuk-button--start' : '')}
          >
            {actionLabel}
            {isStart ? (
              <svg
                className="govuk-button__start-icon"
                xmlns="http://www.w3.org/2000/svg"
                width="17.5"
                height="19"
                viewBox="0 0 33 40"
                aria-hidden="true"
                focusable="false"
              >
                <path fill="currentColor" d="M0 0h13l20 20-20 20H0l20-20z" />
              </svg>
            ) : null}
          </button>
        </form>
      )}
    </Layout>
  )
}
`

