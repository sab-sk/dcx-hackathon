const JOURNEY_LIB = `import journey from '../journey.json'

export const steps = journey.steps
export const service = journey.title

export function slug(text) {
  return String(text == null ? '' : text)
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, '-')
    .replace(/(^-|-$)/g, '')
}

export const routePaths = (function () {
  const seen = {}
  return steps.map(function (step, i) {
    let p
    if (i === 0) p = '/'
    else if (step.url && step.url.charAt(0) === '/') p = step.url
    else p = '/' + (slug(step.title) || 'page-' + (i + 1))
    if (seen[p]) p = p + '-' + i
    seen[p] = true
    return p
  })
})()

export function fieldKey(step, comp, i) {
  return (slug(comp.label) || comp.type + '-' + i) + '-' + step.id
}

export const FIELD_TYPES = ['text-input', 'textarea', 'radios', 'checkboxes', 'date-input', 'file-upload']
`

