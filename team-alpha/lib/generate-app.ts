import JSZip from 'jszip'
import type { Journey } from './journey-schema'

/**
 * Builds a complete, runnable Vite + React + React Router application from a
 * Journey and returns it as a ZIP Blob. Every journey step becomes its own
 * page file and route; shared GOV.UK components, styling, validation and
 * routing logic are emitted as real source files so the download runs with
 * `npm install && npm run dev`.
 */
export async function generateAppZip(journey: Journey): Promise<Blob> {
  const zip = new JSZip()
  const files = buildFiles(journey)
  for (const [path, content] of Object.entries(files)) {
    zip.file(path, content)
  }
  return zip.generateAsync({ type: 'blob' })
}

export function buildFiles(journey: Journey): Record<string, string> {
  const files: Record<string, string> = {}
  const serviceTitle = journey.title || 'GOV.UK service'

  files['package.json'] = PACKAGE_JSON
  files['README.md'] = readme(serviceTitle)
  files['.gitignore'] = GITIGNORE
  files['vite.config.js'] = VITE_CONFIG
  files['index.html'] = indexHtml(serviceTitle)
  files['public/favicon.svg'] = FAVICON_SVG

  files['src/main.jsx'] = MAIN_JSX
  files['src/App.jsx'] = appJsx(journey)
  files['src/store.jsx'] = STORE_JSX
  files['src/journey.json'] = JSON.stringify(journey, null, 2)
  files['src/lib/journey.js'] = JOURNEY_LIB
  files['src/styles/govuk.css'] = GOVUK_CSS

  files['src/components/Layout.jsx'] = LAYOUT_JSX
  files['src/components/BackLink.jsx'] = BACKLINK_JSX
  files['src/components/ErrorSummary.jsx'] = ERROR_SUMMARY_JSX
  files['src/components/JourneyPage.jsx'] = JOURNEY_PAGE_JSX

  journey.steps.forEach((_, i) => {
    const n = i + 1
    files[`src/pages/Page${n}.jsx`] =
      `import JourneyPage from '../components/JourneyPage.jsx'\n\n` +
      `export default function Page${n}() {\n  return <JourneyPage index={${i}} />\n}\n`
  })

  return files
}

