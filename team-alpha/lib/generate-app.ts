function appJsx(journey: Journey): string {
  const imports = journey.steps
    .map((_, i) => `import Page${i + 1} from './pages/Page${i + 1}.jsx'`)
    .join('\n')
  const list = journey.steps.map((_, i) => `Page${i + 1}`).join(', ')

  return `import { Routes, Route } from 'react-router-dom'
import { FormProvider } from './store.jsx'
import { routePaths } from './lib/journey.js'
${imports}

const pages = [${list}]

export default function App() {
  return (
    <FormProvider>
      <Routes>
        {routePaths.map((path, i) => {
          const Page = pages[i]
          return <Route key={path} path={path} element={<Page />} />
        })}
        <Route path="*" element={<Page1 />} />
      </Routes>
    </FormProvider>
  )
}
`
}

function indexHtml(serviceTitle: string): string {
  return `<!doctype html>
<html lang="en" class="govuk-template">
  <head>
    <meta charset="UTF-8" />
    <meta name="viewport" content="width=device-width, initial-scale=1.0" />
    <link rel="icon" type="image/svg+xml" href="/favicon.svg" />
    <title>${escapeHtml(serviceTitle)}</title>
  </head>
  <body class="govuk-template__body">
    <div id="root"></div>
    <script type="module" src="/src/main.jsx"></script>
  </body>
</html>
`
}

function readme(serviceTitle: string): string {
  return `# ${serviceTitle}

A complete GOV.UK-styled service prototype generated by **GDS Journey Builder**.
It is a Vite + React application that uses React Router to connect every page in
the journey, with client-side validation and shared accessible components.

## Requirements

- Node.js 18 or newer

## Setup

Install dependencies and start the development server:

    npm install
    npm run dev

Then open the local URL printed in the terminal (usually http://localhost:5173).

## Production build

    npm run build
    npm run preview

## Project structure

- index.html — app entry document
- src/main.jsx — React entry point and router setup
- src/App.jsx — route definitions, one route per journey step
- src/journey.json — the journey definition this app was generated from
- src/lib/journey.js — derived steps, route paths and field helpers
- src/store.jsx — form state shared across pages
- src/pages/ — one page component per journey step
- src/components/ — shared GOV.UK layout, back link, error summary and page renderer
- src/styles/govuk.css — GOV.UK styling
- public/ — static assets

## How navigation works

Pages are rendered in the same order as the journey. Each page validates its
required fields, shows an error summary when something is missing, and moves to
the next page on Continue. A Back link returns to the previous page. The
check-your-answers page lists earlier answers, and the confirmation page shows a
success panel.
`
}

